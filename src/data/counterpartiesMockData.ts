export const mockCounterparties: Counterparty[] = isDev() ? rawCounterparties : [];

export function getCounterparty(id?: string): Counterparty | undefined {
  if (!id) return undefined;
  return rawCounterparties.find((c) => c.id === id);
}

export function getCounterpartyName(id?: string, fallback: string = '-'): string {
  if (!id) return fallback;
  const found = getCounterparty(id);
  return found ? found.name : fallback;
}
